import AVFoundation
import CoreGraphics
import CoreText
import Foundation
import ImageIO
import UniformTypeIdentifiers

/// Writes a content folder of generated test-pattern "signs" (ADR 0003
/// P10-S8): each clip is a coloured square with its gloss and a moving bar,
/// so playback and looping can be seen. No person is filmed, so the result can
/// live in the repository and in Debug builds. It's never a real sign.
public enum TestPatternContent {
    struct Sign {
        let gloss: String
        let rgb: (CGFloat, CGFloat, CGFloat)
        /// signs.csv cells after idGloss: note, forms:en, forms:ta, reviewStatus.
        let rows: [(note: String, en: String, ta: String)]
        let status: String
    }

    static let signs = [
        Sign(gloss: "WATER", rgb: (0.15, 0.45, 0.85), rows: [("drinking water", "water|waters", "தண்ணீர்|தண்ணி|வாட்டர்")], status: "approved"),
        Sign(gloss: "HELLO", rgb: (0.20, 0.65, 0.40), rows: [("greeting", "hello|hi", "ஹலோ|வணக்கம்")], status: "approved"),
        Sign(gloss: "BANK", rgb: (0.80, 0.55, 0.15), rows: [("money", "bank", "பேங்க்|வங்கி"), ("river", "bank|riverbank", "கரை")], status: "approved"),
        Sign(gloss: "TEA", rgb: (0.65, 0.25, 0.55), rows: [("drink", "tea", "டீ|தேநீர்")], status: "draft"),
    ]

    static let side = 160
    static let fps: Int32 = 15
    static let frames = 18  // 1.2 s

    public static func write(to folder: URL) async throws {
        let fm = FileManager.default
        guard !fm.fileExists(atPath: folder.path(percentEncoded: false)) else {
            throw SignPackBuildError.content("\(folder.path(percentEncoded: false)) already exists; choose a new folder")
        }
        try fm.createDirectory(at: folder.appending(path: "clips"), withIntermediateDirectories: true)
        var csv = "idGloss,note,forms:en,forms:ta,clip,poster,signerId,signerCredit,reviewStatus\n"
        for sign in signs {
            let name = sign.gloss.lowercased()
            try await writeClip(sign, to: folder.appending(path: "clips/\(name).mp4"))
            try writePoster(sign, to: folder.appending(path: "clips/\(name).jpg"))
            for row in sign.rows {
                csv += "\(sign.gloss),\(row.note),\(row.en),\(row.ta),clips/\(name).mp4,clips/\(name).jpg,TP,Generated test pattern,\(sign.status)\n"
            }
        }
        try Data(csv.utf8).write(to: folder.appending(path: "signs.csv"))
        try Data("""
        { "packId": "test-XX-pattern-1", "signLanguage": "zxx", "signLanguageName": "Test pattern (not a sign language)",
          "variety": "Generated for tests", "region": "XX", "defaultForRegions": [], "headwordLanguages": ["en", "ta"],
          "source": { "organisation": "Generated by signpack testpattern", "kind": "generated" },
          "licenceId": "LicenseRef-Saptham-TestPattern", "version": "1", "minAppVersion": "1.0" }
        """.utf8).write(to: folder.appending(path: "pack.json"))
        try Data("Generated test pattern. No person appears in it. Part of Saptham, Apache-2.0.\n".utf8)
            .write(to: folder.appending(path: "LICENSE.txt"))
    }

    // MARK: - Drawing

    private static func draw(_ sign: Sign, frame: Int, in context: CGContext) {
        let size = CGFloat(side)
        context.setFillColor(CGColor(srgbRed: sign.rgb.0, green: sign.rgb.1, blue: sign.rgb.2, alpha: 1))
        context.fill(CGRect(x: 0, y: 0, width: size, height: size))
        // A bar sweeping left to right once per loop.
        let x = size * CGFloat(frame) / CGFloat(frames)
        context.setFillColor(CGColor(gray: 1, alpha: 0.85))
        context.fill(CGRect(x: x, y: 18, width: 14, height: 14))
        let font = CTFontCreateWithName("Helvetica-Bold" as CFString, 24, nil)
        let text = NSAttributedString(string: sign.gloss, attributes: [
            NSAttributedString.Key(kCTFontAttributeName as String): font,
            NSAttributedString.Key(kCTForegroundColorAttributeName as String): CGColor(gray: 1, alpha: 1),
        ])
        let line = CTLineCreateWithAttributedString(text)
        let width = CTLineGetTypographicBounds(line, nil, nil, nil)
        context.textPosition = CGPoint(x: (size - CGFloat(width)) / 2, y: size / 2 - 8)
        CTLineDraw(line, context)
    }

    private static func writeClip(_ sign: Sign, to url: URL) async throws {
        let writer = try AVAssetWriter(outputURL: url, fileType: .mp4)
        let input = AVAssetWriterInput(mediaType: .video, outputSettings: [
            AVVideoCodecKey: AVVideoCodecType.hevc, AVVideoWidthKey: side, AVVideoHeightKey: side,
            AVVideoCompressionPropertiesKey: [AVVideoAverageBitRateKey: 120_000],
        ])
        input.expectsMediaDataInRealTime = false
        let adaptor = AVAssetWriterInputPixelBufferAdaptor(assetWriterInput: input, sourcePixelBufferAttributes: [
            kCVPixelBufferPixelFormatTypeKey as String: kCVPixelFormatType_32BGRA,
            kCVPixelBufferWidthKey as String: side, kCVPixelBufferHeightKey as String: side,
        ])
        writer.add(input)
        guard writer.startWriting() else { throw SignPackBuildError.content("couldn't start writing \(url.lastPathComponent)") }
        writer.startSession(atSourceTime: .zero)
        for frame in 0..<frames {
            while !input.isReadyForMoreMediaData { try await Task.sleep(for: .milliseconds(5)) }
            guard let pool = adaptor.pixelBufferPool else { throw SignPackBuildError.content("no pixel buffer pool") }
            var buffer: CVPixelBuffer?
            CVPixelBufferPoolCreatePixelBuffer(nil, pool, &buffer)
            guard let buffer else { throw SignPackBuildError.content("no pixel buffer") }
            CVPixelBufferLockBaseAddress(buffer, [])
            if let context = CGContext(data: CVPixelBufferGetBaseAddress(buffer), width: side, height: side, bitsPerComponent: 8,
                                       bytesPerRow: CVPixelBufferGetBytesPerRow(buffer), space: CGColorSpace(name: CGColorSpace.sRGB) ?? CGColorSpaceCreateDeviceRGB(),
                                       bitmapInfo: CGImageAlphaInfo.premultipliedFirst.rawValue | CGBitmapInfo.byteOrder32Little.rawValue) {
                draw(sign, frame: frame, in: context)
            }
            CVPixelBufferUnlockBaseAddress(buffer, [])
            guard adaptor.append(buffer, withPresentationTime: CMTime(value: CMTimeValue(frame), timescale: fps)) else {
                throw SignPackBuildError.content("couldn't write a frame of \(url.lastPathComponent)")
            }
        }
        input.markAsFinished()
        // The last frame lasts one frame's time.
        writer.endSession(atSourceTime: CMTime(value: CMTimeValue(frames), timescale: fps))
        await writer.finishWriting()
        guard writer.status == .completed else { throw SignPackBuildError.content("couldn't finish \(url.lastPathComponent)") }
    }

    private static func writePoster(_ sign: Sign, to url: URL) throws {
        guard let context = CGContext(data: nil, width: side, height: side, bitsPerComponent: 8, bytesPerRow: 0,
                                      space: CGColorSpace(name: CGColorSpace.sRGB) ?? CGColorSpaceCreateDeviceRGB(),
                                      bitmapInfo: CGImageAlphaInfo.noneSkipLast.rawValue) else {
            throw SignPackBuildError.content("couldn't draw \(url.lastPathComponent)")
        }
        draw(sign, frame: 0, in: context)
        guard let image = context.makeImage(),
              let destination = CGImageDestinationCreateWithURL(url as CFURL, UTType.jpeg.identifier as CFString, 1, nil) else {
            throw SignPackBuildError.content("couldn't write \(url.lastPathComponent)")
        }
        CGImageDestinationAddImage(destination, image, [kCGImageDestinationLossyCompressionQuality: 0.7] as CFDictionary)
        guard CGImageDestinationFinalize(destination) else { throw SignPackBuildError.content("couldn't write \(url.lastPathComponent)") }
    }
}
